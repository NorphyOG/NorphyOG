def text(x: int, y: int, value: str, *, size: int = 18,
         color: str = TEXT, css_class: str = "", bold: bool = False,
         anchor: str | None = None) -> str:
    """Escape text and retain the spacing needed by the ASCII wordmark."""
    attributes = [f'x="{x}"', f'y="{y}"', f'font-size="{size}"',
                  f'fill="{color}"', 'xml:space="preserve"']
    if css_class:
        attributes.append(f'class="{css_class}"')
    if bold:
        attributes.append('font-weight="700"')
    if anchor:
        attributes.append(f'text-anchor="{anchor}"')
    return f"  <text {' '.join(attributes)}>{escape(value)}</text>"


def document(title: str, description: str, height: int,
             content: list[str], animated_lines: int, *,
             definitions: str = "", extra_css: str = "") -> str:
    """Wrap art in accessible SVG chrome with one short entrance animation.

    Content is visible by default. Viewers without CSS animation support get a
    complete static card, and reduced-motion viewers bypass the entrance.
    """
    delays = "\n".join(
        f"    .line-{index} {{ animation-delay: {index * 90}ms; }}"
        for index in range(animated_lines)
    )
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate_static_art.py; edit the generator. -->
<svg xmlns="http://www.w3.org/2000/svg" width="480" height="{height}"
     viewBox="0 0 480 {height}" role="img" aria-labelledby="title description">
  <title id="title">{escape(title)}</title>
  <desc id="description">{escape(description)}</desc>
{definitions}
  <style>
    text {{ font-family: {FONT}; }}
    .reveal {{ opacity: 1; animation: print-line 420ms ease-out both; }}
{delays}
    @keyframes print-line {{
      from {{ opacity: 0; transform: translateY(3px); }}
      to {{ opacity: 1; transform: translateY(0); }}
    }}
    @media (prefers-reduced-motion: reduce) {{
      .reveal {{ animation: none; opacity: 1; transform: none; }}
    }}
{extra_css}
  </style>
  <rect x="1" y="1" width="478" height="{height - 2}" rx="16"
        fill="{BACKGROUND}" stroke="{BORDER}"/>
  <path d="M17 1 H463 Q479 1 479 17 V47 H1 V17 Q1 1 17 1 Z"
        fill="{SURFACE}"/>
  <path d="M1 47 H479" stroke="{BORDER}"/>
  <circle cx="22" cy="24" r="4" fill="{GREEN}"/>
  <circle cx="37" cy="24" r="4" fill="{MUTED}"/>
  <circle cx="52" cy="24" r="4" fill="{BLUE}"/>
{chr(10).join(content)}
</svg>
'''


