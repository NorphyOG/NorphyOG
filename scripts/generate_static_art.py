def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="Verify generated assets without modifying files.")
    args = parser.parse_args()
    assets = {
        ROOT / "assets" / "terminal-mark.svg": terminal_mark(),
        ROOT / "assets" / "info-card.svg": info_card(),
        ROOT / "assets" / "scanora-banner.svg": scanora_banner(),
        ROOT / "assets" / "portfolio-hero.svg": portfolio_hero(),
        ROOT / "assets" / "pdf-sorter-cover.svg": pdf_sorter_cover(),
        ROOT / "assets" / "cutoversignal-cover.svg": cutoversignal_cover(),
    }
    for svg in assets.values():
        ET.fromstring(svg)
    outdated = []
    for path, svg in assets.items():
        if args.check:
            if not path.exists() or path.read_bytes() != svg.encode("utf-8"):
                outdated.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(svg.encode("utf-8"))
            print(f"Generated {path.relative_to(ROOT)}")
    if outdated:
        for path in outdated:
            print(f"Outdated or missing: {path}", file=sys.stderr)
        print("Run python3 scripts/generate_static_art.py", file=sys.stderr)
        return 1
    if args.check:
        print("Static profile assets are up to date.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
